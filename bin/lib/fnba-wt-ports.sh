# Shared port-block helpers for human fnba-cli worktrees. Sourced, not executed.
# Contract: one registry line "<base>\t<slug>" in
# ${FNBA_CONFIG_DIR:-${HOME}/.config/fnba}/worktree-ports.
# Slug is fnba_db_slug of the branch (caller passes it). Rails is base,
# Vite is base+1. Scan starts at 4100, step 10, max 64000.
# backend/.env.local: FNBA_PORT_BASE, PORT, FRONTEND_PORT,
#   FNBA_HOST_SLUG, FRONTEND_ORIGIN=http://<hs>.fnba.localhost:8080.
# frontend/.env.local: VITE_PORT, VITE_API_URL=http://127.0.0.1:<base>.
# The primary checkout keeps 3000/5173 and gets no port block and no site.
# fnba_allocate_port_block prints only the base on stdout.
# Caddy is plain HTTP on :8080, admin localhost:2029. One site per worktree
# reverse-proxies <hs>.fnba.localhost:8080 to Vite on base+1.

FNBA_CONFIG_DIR="${FNBA_CONFIG_DIR:-${HOME}/.config/fnba}"
FNBA_PORT_REGISTRY="${FNBA_CONFIG_DIR}/worktree-ports"
FNBA_PORT_BASE_START=4100
FNBA_PORT_BASE_STEP=10
FNBA_PORT_BASE_MAX=64000
FNBA_CADDYFILE="${FNBA_CONFIG_DIR}/Caddyfile"
FNBA_CADDY_SITES_DIR="${FNBA_CONFIG_DIR}/caddy"
FNBA_PROXY_PORT=8080
FNBA_CADDY_ADMIN=localhost:2029
FNBA_CADDY_ADMIN_PORT=2029

fnba_port_listening() {
    lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1
}

fnba_host_slug() {
    printf '%s' "$1" | tr '_A-Z' '-a-z'
}

fnba_worktree_origin() {
    printf 'http://%s.fnba.localhost:8080\n' "$(fnba_host_slug "$1")"
}

fnba_dev_proxy_running() {
    fnba_port_listening "$FNBA_CADDY_ADMIN_PORT"
}

fnba_ensure_caddyfile() {
    local placeholder="${FNBA_CADDY_SITES_DIR}/_placeholder.caddy"
    mkdir -p "$FNBA_CADDY_SITES_DIR"
    if [ ! -f "$placeholder" ]; then
        # Comment only: keeps "import caddy/*.caddy" non-empty with no bind.
        printf '%s\n' '# placeholder so import caddy/*.caddy is non-empty' > "$placeholder"
    fi
    if [ ! -f "$FNBA_CADDYFILE" ] || ! grep -F -q 'admin localhost:2029' "$FNBA_CADDYFILE"; then
        printf '%s\n' \
            '# Dev proxy for FNBA per-worktree stacks (managed by fnba-cli wt). Run: bin/dev-proxy' \
            '{' \
            $'\tadmin localhost:2029' \
            $'\tdefault_bind 127.0.0.1' \
            '}' \
            'import caddy/*.caddy' \
            > "$FNBA_CADDYFILE"
    fi
}

fnba_write_caddy_site() {
    local slug="$1"
    local base="$2"
    local hs vite_port site
    hs=$(fnba_host_slug "$slug")
    vite_port=$((base + 1))
    fnba_ensure_caddyfile
    site="${FNBA_CADDY_SITES_DIR}/${hs}.caddy"
    {
        printf '# generated by fnba-cli wt for %s; removed by fnba-cli wt-remove\n' "$hs"
        printf 'http://%s.fnba.localhost:8080 {\n' "$hs"
        printf '\treverse_proxy 127.0.0.1:%s\n' "$vite_port"
        printf '}\n'
    } > "$site"
    printf '%s\n' "$site"
}

# 0 when a site file was removed, 1 otherwise. Never removes _placeholder.caddy.
fnba_remove_caddy_site() {
    local site="${FNBA_CADDY_SITES_DIR}/$(fnba_host_slug "$1").caddy"
    if [ -f "$site" ]; then
        rm -f -- "$site"
        return 0
    fi
    return 1
}

# Always returns 0. bin/git-wt is set -e; a missing proxy or a failed reload
# must not abort worktree create. The site file is already on disk.
fnba_reload_caddy() {
    if ! command -v caddy >/dev/null 2>&1; then
        printf '%s\n' "brew install caddy && bin/dev-proxy"
        return 0
    fi
    if ! fnba_dev_proxy_running; then
        printf '%s\n' "start it once per machine: bin/dev-proxy"
        return 0
    fi
    if caddy reload --config "$FNBA_CADDYFILE" --address "$FNBA_CADDY_ADMIN"; then
        printf '%s\n' "Reloaded ${FNBA_CADDYFILE}"
    else
        printf '%b\n' "${RED:-}caddy reload failed — site file is on disk. Retry: caddy reload --config ${FNBA_CADDYFILE} --address ${FNBA_CADDY_ADMIN}${NC:-}" >&2
    fi
    return 0
}

fnba_registered_port_base() {
    local slug="$1"
    [ -f "$FNBA_PORT_REGISTRY" ] || return 0
    awk -F '\t' -v slug="$slug" '$2 == slug { print $1; exit }' "$FNBA_PORT_REGISTRY"
}

fnba_port_base_registered() {
    local base="$1"
    [ -f "$FNBA_PORT_REGISTRY" ] || return 1
    awk -F '\t' -v base="$base" '
        $1 == base { found = 1; exit }
        END { exit (found ? 0 : 1) }
    ' "$FNBA_PORT_REGISTRY"
}

# Stdout is only the base so command substitution stays clean. Messages go to stderr.
fnba_allocate_port_block() {
    local slug="$1"
    local base registered

    mkdir -p "$FNBA_CONFIG_DIR"
    touch "$FNBA_PORT_REGISTRY"

    registered=$(fnba_registered_port_base "$slug")
    if [ -n "$registered" ]; then
        printf '%s\n' "$registered"
        return 0
    fi

    base="$FNBA_PORT_BASE_START"
    while [ "$base" -le "$FNBA_PORT_BASE_MAX" ]; do
        if fnba_port_base_registered "$base" \
            || fnba_port_listening "$base" \
            || fnba_port_listening "$((base + 1))"; then
            base=$((base + FNBA_PORT_BASE_STEP))
            continue
        fi
        printf '%s\t%s\n' "$base" "$slug" >> "$FNBA_PORT_REGISTRY"
        printf '%s\n' "$base"
        return 0
    done

    printf 'No free port block from %s to %s (step %s)\n' \
        "$FNBA_PORT_BASE_START" "$FNBA_PORT_BASE_MAX" "$FNBA_PORT_BASE_STEP" >&2
    return 1
}

fnba_release_port_block() {
    local slug="$1"
    local base="${2:-}"
    local tmp
    [ -f "$FNBA_PORT_REGISTRY" ] || return 0
    tmp="${FNBA_PORT_REGISTRY}.tmp"
    # print $0 keeps the tab; a bare print would rejoin fields with spaces.
    awk -F '\t' -v slug="$slug" -v base="$base" '
        $2 == slug { next }
        base != "" && $1 == base { next }
        { print $0 }
    ' "$FNBA_PORT_REGISTRY" > "$tmp"
    mv "$tmp" "$FNBA_PORT_REGISTRY"
}

fnba_write_port_block() {
    local worktree="$1"
    local base="$2"
    local slug="$3"
    local backend="${worktree}/backend"
    local frontend="${worktree}/frontend"
    local vite_port=$((base + 1))
    local hs origin
    hs=$(fnba_host_slug "$slug")
    origin=$(fnba_worktree_origin "$slug")

    mkdir -p "$backend" "$frontend"

    if grep -qE '^FNBA_PORT_BASE=' "${backend}/.env.local" 2>/dev/null; then
        return 0
    fi

    {
        echo ""
        echo "# Per-worktree port block (managed by fnba-cli wt)"
        echo "FNBA_PORT_BASE=${base}"
        echo "PORT=${base}"
        echo "FRONTEND_PORT=${vite_port}"
        echo "FNBA_HOST_SLUG=${hs}"
        echo "FRONTEND_ORIGIN=${origin}"
    } >> "${backend}/.env.local"
    {
        echo ""
        echo "# Per-worktree port block (managed by fnba-cli wt)"
        echo "VITE_PORT=${vite_port}"
        echo "VITE_API_URL=http://127.0.0.1:${base}"
    } >> "${frontend}/.env.local"
    echo "Appended port block Rails :${base} Vite :${vite_port}"
    echo "${origin}"
}
